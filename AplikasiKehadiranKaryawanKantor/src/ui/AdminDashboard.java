    private void btnEditDeptActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditDeptActionPerformed
int row = tblDepartemen.getSelectedRow();
    if (row == -1) {
        JOptionPane.showMessageDialog(this, "Pilih departemen yang ingin diedit!"); // Validasi klik tabel
        return;
    }

    DefaultTableModel model = (DefaultTableModel) tblDepartemen.getModel();
    JTextField idField = new JTextField(model.getValueAt(row, 0).toString());
    JTextField namaField = new JTextField(model.getValueAt(row, 1).toString());

    Object[] inputFields = {"ID Departemen:", idField, "Nama Departemen:", namaField};

    int option = JOptionPane.showConfirmDialog(this, inputFields, "Edit Departemen", JOptionPane.OK_CANCEL_OPTION);
    if (option == JOptionPane.OK_OPTION) {
        model.setValueAt(idField.getText(), row, 0); // Update baris yang dipilih
        model.setValueAt(namaField.getText(), row, 1);
    }        // TODO add your handling code here:
    }//GEN-LAST:event_btnEditDeptActionPerformed

