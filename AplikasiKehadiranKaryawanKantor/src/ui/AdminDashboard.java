    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
int row = tblKehadiran.getSelectedRow();
    if (row == -1) {
        JOptionPane.showMessageDialog(this, "Pilih baris di tabel kehadiran dulu!");
        return;
    }

    String[] pilihanStatus = {"Hadir", "Izin", "Sakit", "Alpa"};
    JComboBox<String> statusCombo = new JComboBox<>(pilihanStatus);
    
    // Ambil status lama dari tabel (kolom indeks 3)
    statusCombo.setSelectedItem(tblKehadiran.getValueAt(row, 3).toString());

    int option = JOptionPane.showConfirmDialog(this, statusCombo, "Update Status Kehadiran", JOptionPane.OK_CANCEL_OPTION);
    
    if (option == JOptionPane.OK_OPTION) {
        tblKehadiran.setValueAt(statusCombo.getSelectedItem().toString(), row, 3);
        JOptionPane.showMessageDialog(this, "Status Berhasil Diperbarui!");
    }        // TODO add your handling code here:
    }//GEN-LAST:event_jButton2ActionPerformed

